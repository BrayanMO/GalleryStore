/**
 * Inicializa los selects de Departamento, Provincia y Distrito
 */
export function initGeoSelectors(deptSelectId = 'checkout-dept', provSelectId = 'checkout-prov', distSelectId = 'checkout-dist') {
  const deptEl = document.getElementById(deptSelectId);
  const provEl = document.getElementById(provSelectId);
  const distEl = document.getElementById(distSelectId);

  if (!deptEl || !provEl || !distEl) return;

  // Llenar Departamentos
  const deptNames = Object.keys(DEPARTAMENTOS_PERU).sort();
  deptEl.innerHTML = `
    <option value="">Selecciona Departamento / Región *</option>
    <option value="Lima">Lima</option>
    <option value="Callao">Callao</option>
    <option disabled>──────────</option>
    ${deptNames.filter(d => d !== 'Lima' && d !== 'Callao').map(d => `<option value="${d}">${d}</option>`).join('')}
  `;

  // Cambio de Departamento -> Poblar Provincias
  deptEl.addEventListener('change', () => {
    const selectedDept = deptEl.value;
    if (!selectedDept || !DEPARTAMENTOS_PERU[selectedDept]) {
      provEl.innerHTML = '<option value="">Primero elige departamento</option>';
      distEl.innerHTML = '<option value="">Primero elige provincia</option>';
      provEl.disabled = true;
      distEl.disabled = true;
      return;
    }

    const provincias = Object.keys(DEPARTAMENTOS_PERU[selectedDept]).sort();
    provEl.innerHTML = `
      <option value="">Selecciona Provincia / Ciudad *</option>
      ${provincias.map(p => `<option value="${p}">${p}</option>`).join('')}
    `;
    provEl.disabled = false;
    distEl.innerHTML = '<option value="">Selecciona Distrito *</option>';
    distEl.disabled = true;

    // Auto-seleccionar si solo hay 1 provincia (ej. Callao o Lima Metropolitana)
    if (provincias.length === 1) {
      provEl.value = provincias[0];
      provEl.dispatchEvent(new Event('change'));
    }
  });

  // Cambio de Provincia -> Poblar Distritos
  provEl.addEventListener('change', () => {
    const selectedDept = deptEl.value;
    const selectedProv = provEl.value;

    if (!selectedDept || !selectedProv || !DEPARTAMENTOS_PERU[selectedDept] || !DEPARTAMENTOS_PERU[selectedDept][selectedProv]) {
      distEl.innerHTML = '<option value="">Primero elige provincia</option>';
      distEl.disabled = true;
      return;
    }

    const distritos = DEPARTAMENTOS_PERU[selectedDept][selectedProv].sort();
    distEl.innerHTML = `
      <option value="">Selecciona Distrito *</option>
      ${distritos.map(d => `<option value="${d}">${d}</option>`).join('')}
    `;
    distEl.disabled = false;
  });

  // Iniciar por defecto en Lima si se desea
  deptEl.value = 'Lima';
  deptEl.dispatchEvent(new Event('change'));
}
